        <h1>Política de Privacidade</h1>
        <p>Plataforma QuemDoa</p>
        <p>Versão 1.0</p>
        <p>Última atualização: 05/08/2026</p>
        <h2>1. Apresentação</h2>
        <p>A presente Política de Privacidade descreve como o QuemDoa coleta, utiliza, armazena, compartilha e protege os dados pessoais de seus usuários durante a utilização da plataforma.</p>
        <p>Nos comprometemos a tratar seus dados pessoais com transparência, segurança e respeito, observando a legislação brasileira, especialmente a Lei nº 13.709/2018 (Lei Geral de Proteção de Dados Pessoais - LGPD), o Marco Civil da Internet e demais normas aplicáveis.</p>
        <p>Ao utilizar a plataforma, você declara ter lido esta Política e compreendido como seus dados pessoais são tratados.</p>
        <h2>2. Quem é o Controlador dos Dados</h2>
        <p>Enquanto a plataforma estiver sendo operada por pessoa física, o Controlador dos Dados é:</p>
        <p>Josias Pereira Bueno</p>
        <p>Responsável pelo tratamento dos dados pessoais coletados por meio da plataforma.</p>
        <p>Contato:</p>
        <p>E-mail: contato@QuemDoa.com.br (substituir pelo canal oficial, caso necessário)</p>
        <p>Caso futuramente a operação da plataforma seja assumida por pessoa jurídica, esta Política será atualizada para refletir o novo controlador.</p>
        <h2>3. Abrangência</h2>
        <p>Esta Política aplica-se a todos os usuários da plataforma, incluindo:</p>
        <ul>
            <li>organizadores de campanhas;</li>
            <li>participantes autenticados;</li>
            <li>participantes que utilizem a plataforma sem criar uma conta;</li>
            <li>visitantes do site.</li>
        </ul>
        <h2>4. Quais Dados Coletamos</h2>
        <p>Os dados coletados variam conforme a forma de utilização da plataforma.</p>
        <ol>
            <li>
                <h3>4.1 Dados fornecidos pelo usuário</h3>
                <p>Poderão ser coletados:</p>
                <ul>
                    <li>nome;</li>
                    <li>sobrenome;</li>
                    <li>endereço de e-mail;</li>
                    <li>senha criptografada (quando houver cadastro por e-mail);</li>
                    <li>identificação fornecida pelo Google (quando utilizado login Google);</li>
                    <li>número de WhatsApp (opcional);</li>
                    <li>informações cadastradas em campanhas (quando organizador).</li>
                </ul>
            </li>
            <li>
                <h3>4.2 Dados das campanhas</h3>
                <p>Ao criar campanhas poderão ser armazenados:</p>
                <ul>
                    <li>nome da campanha;</li>
                    <li>descrição;</li>
                    <li>nome da instituição organizadora;</li>
                    <li>nome do grupo, movimento ou pastoral responsável;</li>
                    <li>itens cadastrados;</li>
                    <li>categorias;</li>
                    <li>quantidades;</li>
                    <li>observações.</li>
                </ul>
                <p>Essas informações poderão ser públicas conforme a finalidade da campanha.</p>
            </li>
            <li>
                <h3>4.3 Dados de participação</h3>
                <p>Quando um participante assumir uma sacola, poderão ser registrados:</p>
                <ul>
                    <li>identificação do participante;</li>
                    <li>data da participação;</li>
                    <li>itens assumidos;</li>
                    <li>situação da sacola;</li>
                    <li>confirmação da participação;</li>
                    <li>registro da entrega, quando realizado pelo organizador.</li>
                </ul>
            </li>
            <li>
                <h3>4.4 Dados coletados automaticamente</h3>
                <p>Durante a utilização da plataforma poderão ser registrados automaticamente:</p>
                <ul>
                    <li>endereço IP;</li>
                    <li>data e horário dos acessos;</li>
                    <li>navegador utilizado;</li>
                    <li>sistema operacional;</li>
                    <li>identificadores técnicos necessários para funcionamento da plataforma;</li>
                    <li>registros de autenticação.</li>
                </ul>
                <p>Esses dados são utilizados para fins de segurança, prevenção a fraudes e melhoria da estabilidade da plataforma.</p>
            </li>
        </ol>
        <h2>5. Dados que Não Coletamos</h2>
        <p>O QuemDoa não coleta, como regra:</p>
        <ul>
            <li>CPF;</li>
            <li>RG;</li>
            <li>endereço residencial;</li>
            <li>dados bancários;</li>
            <li>informações de cartão de crédito;</li>
            <li>biometria;</li>
            <li>geolocalização precisa;</li>
            <li>dados sensíveis definidos pela LGPD (como origem racial, convicção religiosa, opiniões políticas, dados de saúde, filiação sindical ou informações biométricas).</li>
        </ul>
        <p>Caso futuramente algum desses dados passe a ser necessário, esta Política será atualizada antes de sua coleta.</p>
        <h2>6. Finalidade do Tratamento dos Dados</h2>
        <p>Os dados pessoais são tratados exclusivamente para finalidades legítimas relacionadas ao funcionamento da plataforma.</p>
        <p>Entre elas:</p>
        <ul>
            <li>criação e administração de contas;</li>
            <li>autenticação de usuários;</li>
            <li>criação de campanhas;</li>
            <li>gerenciamento das sacolas;</li>
            <li>confirmação de participações;</li>
            <li>comunicação entre plataforma e usuário;</li>
            <li>recuperação de senha;</li>
            <li>prevenção a fraudes;</li>
            <li>segurança da plataforma;</li>
            <li>cumprimento de obrigações legais;</li>
            <li>melhoria da experiência de utilização.</li>
        </ul>
        <p>Os dados não serão utilizados para finalidades incompatíveis com aquelas informadas nesta Política.</p>
        <h2>7. Bases Legais do Tratamento</h2>
        <p>O tratamento de dados pessoais realizado pelo QuemDoa poderá fundamentar-se, conforme cada situação, nas seguintes bases legais previstas pela LGPD:</p>
        <ul>
            <li>execução de contrato ou de procedimentos preliminares solicitados pelo titular;</li>
            <li>cumprimento de obrigação legal ou regulatória;</li>
            <li>exercício regular de direitos;</li>
            <li>legítimo interesse do controlador, respeitados os direitos e liberdades fundamentais do titular;</li>
            <li>consentimento do titular, quando exigido pela legislação.</li>
        </ul>
        <p>Cada tratamento observará a base legal mais adequada à sua finalidade.</p>
        <h2>8. Dados de Menores de Idade</h2>
        <p>O cadastro na plataforma destina-se a pessoas com 18 (dezoito) anos ou mais.</p>
        <p>Caso seja identificado tratamento de dados de menor realizado em desacordo com esta Política ou com a legislação aplicável, o QuemDoa poderá excluir a conta e os respectivos dados pessoais, ressalvadas as hipóteses de conservação previstas em lei.</p>
        <p>A participação em campanhas poderá ocorrer por intermédio de pais, mães ou responsáveis legais.</p>
        <h2>9. Compartilhamento de Dados</h2>
        <p>O QuemDoa não comercializa dados pessoais.</p>
        <p>Os dados poderão ser compartilhados apenas quando necessário para:</p>
        <ul>
            <li>funcionamento da plataforma;</li>
            <li>autenticação por provedores de login;</li>
            <li>hospedagem da infraestrutura;</li>
            <li>cumprimento de obrigação legal;</li>
            <li>atendimento de determinação judicial ou administrativa;</li>
            <li>exercício regular de direitos.</li>
        </ul>
        <p>Os organizadores terão acesso apenas às informações necessárias para identificar os participantes de suas próprias campanhas.</p>
        <p>Jamais serão disponibilizados dados de campanhas de terceiros sem fundamento legal.</p>
        <h2>10. Armazenamento dos Dados</h2>
        <p>Os dados pessoais tratados pelo QuemDoa são armazenados em infraestrutura computacional contratada junto a fornecedores especializados, que adotam medidas técnicas e organizacionais destinadas à proteção das informações.</p>
        <p>Atualmente, os dados são armazenados em servidores localizados fora do território brasileiro.</p>
        <p>Sempre que houver transferência internacional de dados pessoais, o QuemDoa buscará assegurar que o tratamento ocorra em conformidade com a LGPD, adotando medidas razoáveis para garantir nível adequado de proteção dos dados.</p>
        <p>A eventual alteração do provedor de hospedagem ou do país onde os dados são armazenados não modifica os direitos assegurados aos titulares pela legislação brasileira.</p>
        <h2>11. Segurança da Informação</h2>
        <p>O QuemDoa adota medidas técnicas e administrativas destinadas a proteger os dados pessoais contra acessos não autorizados, destruição, perda, alteração, divulgação ou qualquer forma de tratamento inadequado ou ilícito.</p>
        <p>Entre essas medidas poderão estar:</p>
        <ul>
            <li>utilização de conexões criptografadas (HTTPS/TLS);</li>
            <li>armazenamento seguro de senhas mediante algoritmos de hash criptográfico;</li>
            <li>controle de acesso aos sistemas;</li>
            <li>autenticação de usuários;</li>
            <li>monitoramento de eventos relacionados à segurança;</li>
            <li>atualizações periódicas da infraestrutura;</li>
            <li>restrição de acesso aos dados conforme necessidade operacional.</li>
        </ul>
        <p>Embora sejam adotadas boas práticas de segurança, nenhum sistema é absolutamente inviolável. Assim, o QuemDoa não pode garantir segurança absoluta contra ataques cibernéticos, falhas imprevisíveis ou atos praticados por terceiros.</p>
        <p>Caso seja identificado incidente de segurança que possa acarretar risco ou dano relevante aos titulares dos dados, serão adotadas as providências cabíveis, inclusive as comunicações exigidas pela legislação aplicável.</p>
        <h2>12. Cookies e Tecnologias Semelhantes</h2>
        <p>O QuemDoa utiliza apenas cookies e tecnologias estritamente necessários ao funcionamento da plataforma e à melhoria da experiência do usuário.</p>
        <p>Esses cookies não têm como finalidade realizar publicidade comportamental ou rastreamento para fins de marketing.</p>
        <p>Atualmente, poderão ser utilizados os seguintes tipos de cookies:</p>
        <ol>
            <li>
                <h3>Cookies de sessão</h3>
                <p>Utilizados para manter a autenticação do usuário durante sua navegação e garantir o funcionamento adequado da plataforma.</p>
                <p>Esses cookies são removidos automaticamente ao término da sessão, salvo quando tecnicamente necessário para manter o login conforme configuração escolhida pelo usuário.</p>
            </li>
            <li>
                <h3>Cookie de recuperação de sacola</h3>
                <p>Quando um participante ainda não autenticado iniciar o preenchimento de uma participação, a plataforma poderá armazenar temporariamente um identificador técnico que permita recuperar a sacola caso a página seja fechada acidentalmente antes da confirmação.</p>
                <p>Esse cookie possui finalidade exclusivamente funcional.</p>
            </li>
            <li>
                <h3>Cookie para memorização do WhatsApp</h3>
                <p>Caso o participante informe voluntariamente seu número de WhatsApp, a plataforma poderá armazená-lo em cookie por até 30 (trinta) dias, permitindo seu preenchimento automático em futuras participações realizadas no mesmo dispositivo e navegador.</p>
                <p>Esse armazenamento tem como única finalidade proporcionar maior comodidade ao usuário.</p>
                <p>O usuário poderá remover esse cookie a qualquer momento por meio das configurações de seu navegador.</p>
            </li>
        </ol>
        <h2>13. Por Quanto Tempo Mantemos os Dados</h2>
        <p>Os dados pessoais serão mantidos apenas pelo tempo necessário para cumprir as finalidades descritas nesta Política, observadas as obrigações legais e regulatórias aplicáveis.</p>
        <p>De forma geral:</p>
        <ul>
            <li>dados cadastrais permanecerão enquanto a conta estiver ativa;</li>
            <li>registros de autenticação poderão ser mantidos pelo período necessário à segurança da plataforma;</li>
            <li>informações relacionadas às campanhas poderão permanecer enquanto a campanha existir ou enquanto necessárias para sua integridade;</li>
            <li>dados excluídos poderão permanecer temporariamente em cópias de segurança (backups), sendo eliminados conforme o ciclo normal de retenção dessas cópias.</li>
        </ul>
        <p>Sempre que possível, dados que não precisem mais identificar seus titulares serão anonimizados.</p>
        <h2>14. Exclusão dos Dados</h2>
        <p>O titular poderá solicitar a exclusão de sua conta e de seus dados pessoais por meio dos canais oficiais disponibilizados pela plataforma.</p>
        <p>Recebida a solicitação, o QuemDoa adotará as providências necessárias para excluir ou anonimizar os dados pessoais cuja conservação não seja exigida por obrigação legal ou regulatória.</p>
        <p>Algumas informações poderão ser preservadas pelo período estritamente necessário para:</p>
        <ul>
            <li>cumprimento de obrigação legal;</li>
            <li>exercício regular de direitos em processos administrativos, arbitrais ou judiciais;</li>
            <li>prevenção de fraudes;</li>
            <li>garantia da integridade histórica das campanhas, mediante anonimização sempre que possível.</li>
        </ul>
        <h2>15. Direitos do Titular dos Dados</h2>
        <p>Nos termos da LGPD, o titular poderá exercer, quando aplicável, os seguintes direitos:</p>
        <ul>
            <li>confirmar a existência de tratamento de seus dados;</li>
            <li>solicitar acesso aos dados pessoais tratados;</li>
            <li>requerer a correção de dados incompletos, inexatos ou desatualizados;</li>
            <li>solicitar a anonimização, bloqueio ou eliminação de dados tratados em desconformidade com a legislação;</li>
            <li>solicitar a portabilidade dos dados, quando tecnicamente viável e observadas as normas da ANPD;</li>
            <li>requerer a eliminação dos dados tratados com base em consentimento, quando aplicável;</li>
            <li>obter informações sobre o compartilhamento de seus dados;</li>
            <li>revogar consentimentos concedidos, quando essa for a base legal utilizada;</li>
            <li>apresentar reclamação perante a Autoridade Nacional de Proteção de Dados (ANPD), na forma da legislação.</li>
        </ul>
        <p>As solicitações serão analisadas dentro dos prazos e condições previstos na legislação aplicável.</p>
        <h2>16. Exercício dos Direitos</h2>
        <p>Para exercer qualquer dos direitos previstos nesta Política ou na LGPD, o titular poderá entrar em contato com o Controlador por meio dos canais oficiais disponibilizados na plataforma.</p>
        <p>Poderá ser necessário solicitar informações adicionais para confirmar a identidade do solicitante, a fim de evitar acesso indevido aos dados pessoais por terceiros.</p>
        <p>Caso determinado pedido não possa ser atendido, o titular será informado das razões legais ou técnicas que justifiquem a impossibilidade de seu atendimento.</p>
        <h2>17. Alterações desta Política</h2>
        <p>Esta Política de Privacidade poderá ser atualizada periodicamente para refletir:</p>
        <ul>
            <li>alterações na legislação;</li>
            <li>evolução das funcionalidades da plataforma;</li>
            <li>melhorias operacionais;</li>
            <li>mudanças nos serviços utilizados;</li>
            <li>novas práticas de segurança;</li>
            <li>alterações no tratamento de dados pessoais.</li>
        </ul>
        <p>A versão mais recente permanecerá sempre disponível na plataforma.</p>
        <p>Quando houver alterações relevantes que afetem significativamente os direitos dos titulares, serão adotadas medidas razoáveis para dar ciência aos usuários.</p>
        <h2>18. Serviços de Terceiros</h2>
        <p>Para viabilizar o funcionamento da plataforma, o QuemDoa poderá utilizar serviços fornecidos por terceiros, sempre que necessários ao desempenho de suas atividades.</p>
        <p>Esses serviços poderão incluir, entre outros:</p>
        <ul>
            <li>autenticação por conta Google;</li>
            <li>envio de mensagens eletrônicas;</li>
            <li>hospedagem de servidores;</li>
            <li>armazenamento de arquivos;</li>
            <li>serviços de infraestrutura em nuvem;</li>
            <li>monitoramento de disponibilidade e segurança.</li>
        </ul>
        <p>Sempre que houver compartilhamento de dados com terceiros, ele ocorrerá apenas na medida necessária para a execução do respectivo serviço e observando, sempre que possível, critérios compatíveis com a legislação aplicável sobre proteção de dados pessoais.</p>
        <p>O uso desses serviços também poderá estar sujeito às respectivas políticas de privacidade e termos de uso de seus fornecedores.</p>
        <h2>19. Login com Google</h2>
        <p>Quando o usuário optar por autenticar-se utilizando uma conta Google, o QuemDoa poderá receber do Google apenas as informações necessárias para identificar o usuário e permitir seu acesso à plataforma.</p>
        <p>Essas informações normalmente incluem:</p>
        <ul>
            <li>nome;</li>
            <li>endereço de e-mail;</li>
            <li>identificador único da conta;</li>
            <li>imagem de perfil, quando disponibilizada pelo próprio usuário junto ao Google.</li>
        </ul>
        <p>O QuemDoa não terá acesso à senha da conta Google nem às demais informações armazenadas pelo provedor que não sejam expressamente compartilhadas para fins de autenticação.</p>
        <p>O usuário poderá revogar essa autorização diretamente nas configurações de sua Conta Google, observadas as regras do respectivo provedor.</p>
        <h2>20. Decisões Automatizadas</h2>
        <p>Atualmente, o QuemDoa não realiza decisões exclusivamente automatizadas que produzam efeitos jurídicos ou afetem significativamente os direitos dos usuários.</p>
        <p>Caso, futuramente, sejam implementados recursos que utilizem inteligência artificial ou algoritmos para sugerir itens, organizar campanhas ou oferecer funcionalidades semelhantes, esta Política será atualizada para refletir essas alterações, indicando as respectivas finalidades, critérios de funcionamento e direitos dos titulares.</p>
        <h2>21. Encarregado pelo Tratamento de Dados</h2>
        <p>Enquanto a plataforma estiver sob operação de pessoa física e não houver designação formal de um Encarregado pelo Tratamento de Dados Pessoais (DPO), as solicitações relacionadas à privacidade poderão ser encaminhadas diretamente ao Controlador dos Dados, por meio dos canais oficiais de contato.</p>
        <p>Caso venha a ser designado um Encarregado ou a legislação passe a exigir sua indicação formal para a operação da plataforma, esta Política será atualizada com as respectivas informações de contato.</p>
        <h2>22. Legislação Aplicável</h2>
        <p>Esta Política de Privacidade é regida pelas leis da República Federativa do Brasil, especialmente:</p>
        <ul>
            <li>Constituição Federal;</li>
            <li>Lei nº 13.709/2018 (Lei Geral de Proteção de Dados Pessoais - LGPD);</li>
            <li>Lei nº 12.965/2014 (Marco Civil da Internet);</li>
            <li>Lei nº 8.078/1990 (Código de Defesa do Consumidor), quando aplicável;</li>
            <li>Código Civil Brasileiro;</li>
            <li>normas complementares expedidas pela Autoridade Nacional de Proteção de Dados (ANPD).</li>
        </ul>
        <h2>23. Contato</h2>
        <p>Em caso de dúvidas, solicitações relacionadas ao tratamento de dados pessoais ou exercício dos direitos previstos na LGPD, o titular poderá entrar em contato pelos canais oficiais da plataforma.</p>
        <p>Controlador dos Dados (provisório): Josias Pereira Bueno</p>
        <p>E-mail: contato@quemdoa.com.</p>
        <p>Sempre que necessário para proteção dos dados pessoais, poderá ser solicitada a confirmação da identidade do titular antes do atendimento da solicitação.</p>
        <h2>24. Alterações desta Política</h2>
        <p>Esta Política poderá ser revisada e atualizada periodicamente para refletir:</p>
        <ul>
            <li>alterações na legislação;</li>
            <li>evolução da plataforma;</li>
            <li>inclusão de novas funcionalidades;</li>
            <li>adoção de novos recursos tecnológicos;</li>
            <li>mudanças nos serviços utilizados;</li>
            <li>aprimoramentos nas práticas de segurança e governança de dados.</li>
        </ul>
        <p>A versão vigente estará sempre disponível para consulta na plataforma.</p>
        <p>Sempre que uma alteração modificar significativamente a forma de tratamento dos dados pessoais ou os direitos dos titulares, o QuemDoa buscará comunicar os usuários por meios adequados antes de sua entrada em vigor.</p>
        <h2>25. Vigência</h2>
        <p>Esta Política entra em vigor na data de sua publicação e permanecerá válida até que seja substituída por versão posterior.</p>
        <p>O uso continuado da plataforma após a publicação de alterações representa ciência da versão vigente, sem prejuízo dos direitos assegurados pela legislação aplicável.</p>
        <h2>Mensagem Final</h2>
        <p>O QuemDoa acredita que confiança é construída por meio da transparência.</p>
        <p>Por esse motivo, buscamos coletar apenas os dados realmente necessários para o funcionamento da plataforma, tratá-los com responsabilidade e permitir que cada usuário exerça, de forma simples, os direitos garantidos pela Lei Geral de Proteção de Dados Pessoais.</p>
        <p>Nosso compromisso é continuar aprimorando continuamente nossas práticas de privacidade e segurança, acompanhando a evolução da legislação, da tecnologia e das necessidades dos usuários.</p>
