        <h2>3. Objeto da Plataforma</h2>
        <p>O QuemDoa possui como finalidade facilitar a organização de campanhas de arrecadação de doações, permitindo que participantes visualizem necessidades previamente cadastradas e escolham espontaneamente quais itens desejam levar.</p>
        <p>A plataforma atua exclusivamente como ferramenta tecnológica de organização e comunicação entre organizadores e participantes.</p>
        <p>O QuemDoa:</p>
        <ul>
            <li>não comercializa produtos;</li>
            <li>não recebe valores referentes às doações;</li>
            <li>não transporta bens;</li>
            <li>não intermedeia pagamentos;</li>
            <li>não garante a entrega das doações;</li>
            <li>não fiscaliza a utilização dos itens arrecadados.</li>
        </ul>
        <p>Toda responsabilidade pela organização, arrecadação, recebimento e destinação das doações pertence exclusivamente à instituição organizadora da campanha.</p>
        <h2>4. Elegibilidade</h2>
        <p>O cadastro de usuários é destinado a pessoas com idade igual ou superior a 18 (dezoito) anos.</p>
        <p>Ao criar uma conta, o usuário declara possuir capacidade civil para aceitar estes Termos.</p>
        <p>Caso seja identificado cadastro realizado em desacordo com esta condição, o QuemDoa poderá suspender ou excluir a conta, independentemente de aviso prévio.</p>
        <p>Nada impede que menores participem das campanhas como doadores juntamente com seus responsáveis, porém a utilização da plataforma deverá ocorrer por intermédio de um adulto responsável.</p>
