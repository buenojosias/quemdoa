        1. APRESENTAÇÃO

Esta Política de Cookies explica como o QuemDoa utiliza cookies e tecnologias semelhantes durante a navegação em sua plataforma.

Nosso objetivo é garantir transparência sobre quais informações são armazenadas em seu dispositivo, por que elas são utilizadas e como você pode gerenciá-las.

Esta Política complementa nossa Política de Privacidade e nossos Termos de Uso.

2. O QUE SÃO COOKIES?

Cookies são pequenos arquivos de texto armazenados em seu navegador ou dispositivo quando você acessa um site ou sistema.

Esses arquivos permitem que determinadas informações sejam lembradas durante a navegação ou em acessos futuros, contribuindo para o funcionamento adequado da plataforma e para uma melhor experiência do usuário.

Os cookies utilizados pelo QuemDoa não executam programas, não contêm vírus e não têm acesso aos demais arquivos armazenados em seu dispositivo.

3. POR QUE UTILIZAMOS COOKIES?

O QuemDoa utiliza cookies exclusivamente para:

garantir o funcionamento adequado da plataforma;
manter a autenticação do usuário durante a navegação;
recuperar uma participação iniciada e não concluída;
evitar que o participante precise informar repetidamente seu número de WhatsApp quando optar por fornecê-lo.

Atualmente, não utilizamos cookies destinados à publicidade comportamental, remarketing ou criação de perfis de navegação.

4. TIPOS DE COOKIES UTILIZADOS
4.1 Cookies Essenciais

São indispensáveis para o funcionamento da plataforma.

Sem esses cookies, determinados recursos poderão deixar de funcionar corretamente.

Esses cookies não exigem consentimento prévio, conforme a legislação aplicável, por serem estritamente necessários para a prestação do serviço solicitado pelo usuário.

Exemplos de utilização:

autenticação de usuários;
gerenciamento de sessão;
proteção contra acessos indevidos;
funcionamento das funcionalidades principais da plataforma.
4.2 Cookie de Recuperação de Sacola

Quando um participante inicia a seleção de itens de uma campanha sem concluir imediatamente sua participação, o QuemDoa poderá armazenar temporariamente um identificador técnico em cookie.

Esse identificador permite recuperar a sacola caso o navegador seja fechado acidentalmente ou a página seja recarregada antes da confirmação da participação.

Esse cookie não é utilizado para identificar hábitos de navegação nem para fins publicitários.

4.3 Cookie de Memorização do WhatsApp

Caso o participante informe voluntariamente seu número de WhatsApp, a plataforma poderá armazená-lo em cookie por até 30 (trinta) dias, permitindo seu preenchimento automático em futuras participações realizadas no mesmo navegador e dispositivo.

Esse recurso existe exclusivamente para oferecer maior praticidade ao usuário.

O número armazenado não é compartilhado com terceiros por meio desse cookie.

5. TABELA DE COOKIES
Cookie	Finalidade	Duração
Sessão	Manter a autenticação e o funcionamento da plataforma durante a navegação	Até o encerramento da sessão ou conforme a opção de login escolhida pelo usuário
Recuperação de Sacola	Restaurar uma participação iniciada e ainda não confirmada	Até a confirmação da participação ou por período técnico limitado
