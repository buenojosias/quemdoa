A nomenclatura técnica dos cookies poderá ser alterada a qualquer momento em razão de atualizações da plataforma, sem modificação de suas respectivas finalidades.

6. COOKIES DE TERCEIROS

Atualmente, o QuemDoa não utiliza cookies de terceiros para publicidade, análise estatística, rastreamento de comportamento ou marketing.

Caso futuramente sejam implementados serviços como ferramentas de estatísticas, mapas de calor ou plataformas de anúncios, esta Política será atualizada antes da utilização desses cookies, observando a legislação aplicável.

7. COMO GERENCIAR OS COOKIES

O usuário pode, a qualquer momento:

visualizar os cookies armazenados pelo navegador;
remover cookies já existentes;
bloquear novos cookies;
configurar o navegador para solicitar autorização antes de armazenar cookies.

Entretanto, o bloqueio de cookies essenciais poderá impedir o funcionamento correto de determinadas funcionalidades do QuemDoa.

8. ALTERAÇÕES DESTA POLÍTICA

Esta Política poderá ser atualizada sempre que houver alterações na forma como o QuemDoa utiliza cookies ou quando houver mudanças na legislação aplicável.

A versão mais recente permanecerá sempre disponível para consulta na plataforma.

Sempre que houver modificações relevantes, os usuários serão informados pelos meios de comunicação disponíveis.

