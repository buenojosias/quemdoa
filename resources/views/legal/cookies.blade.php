        <h2>6. Cookies de Terceiros</h2>
        <p>Atualmente, o QuemDoa não utiliza cookies de terceiros para publicidade, análise estatística, rastreamento de comportamento ou marketing.</p>
        <p>Caso futuramente sejam implementados serviços como ferramentas de estatísticas, mapas de calor ou plataformas de anúncios, esta Política será atualizada antes da utilização desses cookies, observando a legislação aplicável.</p>
        <h2>7. Como Gerenciar os Cookies</h2>
        <p>O usuário pode, a qualquer momento:</p>
        <ul>
            <li>visualizar os cookies armazenados pelo navegador;</li>
            <li>remover cookies já existentes;</li>
            <li>bloquear novos cookies;</li>
            <li>configurar o navegador para solicitar autorização antes de armazenar cookies.</li>
        </ul>
        <p>Entretanto, o bloqueio de cookies essenciais poderá impedir o funcionamento correto de determinadas funcionalidades do QuemDoa.</p>
