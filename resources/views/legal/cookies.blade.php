        <h1>Política de Cookies</h1>
        <p>Plataforma QuemDoa</p>
        <p>Versão 1.0</p>
        <p>Última atualização: 05/08/2026</p>
        <h2>1. Apresentação</h2>
        <p>Esta Política de Cookies explica como o QuemDoa utiliza cookies e tecnologias semelhantes durante a navegação em sua plataforma.</p>
        <p>Nosso objetivo é garantir transparência sobre quais informações são armazenadas em seu dispositivo, por que elas são utilizadas e como você pode gerenciá-las.</p>
        <p>Esta Política complementa nossa Política de Privacidade e nossos Termos de Uso.</p>
        <h2>2. O que São Cookies?</h2>
        <p>Cookies são pequenos arquivos de texto armazenados em seu navegador ou dispositivo quando você acessa um site ou sistema.</p>
        <p>Esses arquivos permitem que determinadas informações sejam lembradas durante a navegação ou em acessos futuros, contribuindo para o funcionamento adequado da plataforma e para uma melhor experiência do usuário.</p>
        <p>Os cookies utilizados pelo QuemDoa não executam programas, não contêm vírus e não têm acesso aos demais arquivos armazenados em seu dispositivo.</p>
        <h2>3. Por que Utilizamos Cookies?</h2>
        <p>O QuemDoa utiliza cookies exclusivamente para:</p>
        <ul>
            <li>garantir o funcionamento adequado da plataforma;</li>
            <li>manter a autenticação do usuário durante a navegação;</li>
            <li>recuperar uma participação iniciada e não concluída;</li>
            <li>evitar que o participante precise informar repetidamente seu número de WhatsApp quando optar por fornecê-lo.</li>
        </ul>
        <p>Atualmente, não utilizamos cookies destinados à publicidade comportamental, remarketing ou criação de perfis de navegação.</p>
        <h2>4. Tipos de Cookies Utilizados</h2>
        <ol>
            <li>
                <h3>4.1 Cookies Essenciais</h3>
                <p>São indispensáveis para o funcionamento da plataforma.</p>
                <p>Sem esses cookies, determinados recursos poderão deixar de funcionar corretamente.</p>
                <p>Esses cookies não exigem consentimento prévio, conforme a legislação aplicável, por serem estritamente necessários para a prestação do serviço solicitado pelo usuário.</p>
                <p>Exemplos de utilização:</p>
                <ul>
                    <li>autenticação de usuários;</li>
                    <li>gerenciamento de sessão;</li>
                    <li>proteção contra acessos indevidos;</li>
                    <li>funcionamento das funcionalidades principais da plataforma.</li>
                </ul>
            </li>
            <li>
                <h3>4.2 Cookie de Recuperação de Sacola</h3>
                <p>Quando um participante inicia a seleção de itens de uma campanha sem concluir imediatamente sua participação, o QuemDoa poderá armazenar temporariamente um identificador técnico em cookie.</p>
                <p>Esse identificador permite recuperar a sacola caso o navegador seja fechado acidentalmente ou a página seja recarregada antes da confirmação da participação.</p>
                <p>Esse cookie não é utilizado para identificar hábitos de navegação nem para fins publicitários.</p>
            </li>
            <li>
                <h3>4.3 Cookie de Memorização do WhatsApp</h3>
                <p>Caso o participante informe voluntariamente seu número de WhatsApp, a plataforma poderá armazená-lo em cookie por até 30 (trinta) dias, permitindo seu preenchimento automático em futuras participações realizadas no mesmo navegador e dispositivo.</p>
                <p>Esse recurso existe exclusivamente para oferecer maior praticidade ao usuário.</p>
                <p>O número armazenado não é compartilhado com terceiros por meio desse cookie.</p>
            </li>
        </ol>
